"""Generate a cricket news draft and branded Instagram image using RSS and Pillow."""
from __future__ import annotations
import re
from datetime import datetime, timezone
from pathlib import Path
from zoneinfo import ZoneInfo
import feedparser
from PIL import Image, ImageDraw, ImageFont

IST = ZoneInfo("Asia/Kolkata")
NEWS_FEED = "https://news.google.com/rss/search?q=cricket+(India+OR+IPL+OR+ICC+OR+Test+OR+ODI+OR+T20)&hl=en-IN&gl=IN&ceid=IN:en"
MAX_ARTICLES = 10

def clean_text(value: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", value)).strip()

def fetch_articles() -> list[dict[str, str]]:
    feed = feedparser.parse(NEWS_FEED)
    items, seen = [], set()
    for entry in feed.entries:
        title, url = clean_text(str(entry.get("title", ""))), str(entry.get("link", "")).strip()
        if not title or not url or url in seen:
            continue
        seen.add(url)
        items.append({"title": title, "url": url, "summary": clean_text(str(entry.get("summary", "")))[:500]})
        if len(items) >= MAX_ARTICLES:
            break
    if not items:
        raise RuntimeError("No cricket articles returned by RSS feed.")
    return items

def font(size: int, bold: bool = False):
    p = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf" if bold else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
    try:
        return ImageFont.truetype(p, size)
    except OSError:
        return ImageFont.load_default()

def wrap(draw, text, f, width):
    result, line = [], ""
    for word in text.split():
        candidate = (line + " " + word).strip()
        if draw.textbbox((0, 0), candidate, font=f)[2] <= width:
            line = candidate
        else:
            if line:
                result.append(line)
            line = word
    if line:
        result.append(line)
    return result

def create_image(title: str, date: str, path: Path):
    # Template-created branded artwork, not generated by an AI image model.
    im = Image.new("RGB", (1080, 1350), (8, 20, 43))
    d = ImageDraw.Draw(im)
    d.rounded_rectangle((48, 48, 1032, 1302), radius=42, fill=(14, 37, 72), outline=(30, 205, 170), width=4)
    d.text((95, 105), "NEXZENCRICINFO", font=font(42, True), fill=(48, 230, 190))
    d.text((95, 170), "CRICKET • NEWS • INSIGHT", font=font(24, True), fill=(190, 215, 240))
    d.line((95, 230, 985, 230), fill=(48, 230, 190), width=3)
    d.text((95, 300), "TODAY'S CRICKET UPDATE", font=font(48, True), fill=(255, 204, 75))
    d.text((95, 385), date, font=font(27), fill=(190, 215, 240))
    d.ellipse((825, 390, 955, 520), fill=(220, 55, 65), outline="white", width=3)
    d.arc((850, 400, 930, 510), 70, 285, fill="white", width=4)
    y, tf = 580, font(42, True)
    for line in wrap(d, title, tf, 820)[:9]:
        d.text((95, y), line, font=tf, fill="white")
        y += 62
    d.rounded_rectangle((95, 1080, 985, 1175), radius=20, fill=(48, 230, 190))
    d.text((130, 1108), "Follow @nexzencricinfo for more", font=font(28, True), fill=(8, 20, 43))
    d.text((95, 1215), "WHERE NEXT GEN CRICKET BEGINS", font=font(24, True), fill=(190, 215, 240))
    path.parent.mkdir(parents=True, exist_ok=True)
    im.save(path, "PNG", optimize=True)

def main():
    today = datetime.now(IST).date().isoformat()
    articles = fetch_articles()
    a = articles[0]
    caption = (f"🏏 CRICKET UPDATE | {today}\n\n{a['title']}\n\n{a['summary'] or 'See source for details.'}\n\n"
               "What do you think? Share your thoughts below!\n\n#Cricket #CricketNews #IndianCricket #ICC #IPL #NexZenCricInfo\n\n"
               f"Source: {a['url']}\n\nWhere Next Gen Cricket Begins")
    Path("drafts").mkdir(exist_ok=True)
    Path("images").mkdir(exist_ok=True)
    draft = (f"# NexZenCricInfo — Cricket Post ({today})\n\n> Template-generated graphic and caption; verify source details.\n\n"
             f"{caption}\n\n## Articles collected\n\n" +
             "\n".join(f"- [{x['title']}]({x['url']})" for x in articles) +
             f"\n\nGenerated at {datetime.now(timezone.utc).isoformat()} (UTC)\n")
    Path("drafts", f"{today}.md").write_text(draft, encoding="utf-8")
    create_image(a["title"], today, Path("images", f"{today}.png"))
    print(f"Draft and graphic created for {today}")

if __name__ == "__main__":
    main()
